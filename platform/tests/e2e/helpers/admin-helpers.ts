export interface SeededPiece {
  id: string;
  name: string;
  modelIds: [string, string];
  storage: { bucket: string; paths: string[] }[];
}

/**
 * A piece in `review` with one photo and two candidates, laid out like the worker:
 * candidate 1 selected at `{piece}/{attempt}/…`, candidate 2 at `{piece}/{attempt}/cand_2/…`.
 */
export async function seedReviewPiece(
  db: SupabaseClient,
  user: TestUser,
  name: string,
  options: { withoutUsdz?: number } = {},
): Promise<SeededPiece> {
  const id = randomUUID();
  const { error: pieceError } = await db.from("pieces").insert({
    id,
    user_id: user.id,
    name,
    kind: "sillon",
    width_cm: 82,
    height_cm: 76.5,
    depth_cm: 80,
    rectilinear: false,
    notes: "test_ pieza de la revisión",
    status: "review",
    attempt: 1,
    route: "organic",
  });
  if (pieceError) throw new Error(`insert piece: ${pieceError.message}`);

  const upload = async (bucket: string, p: string, body: Buffer, contentType: string) => {
    const { error } = await db.storage.from(bucket).upload(p, body, { contentType, upsert: true });
    if (error) throw new Error(`upload ${bucket}/${p}: ${error.message}`);
    return p;
  };

  const photo = await upload("photos", `${user.id}/${id}/1.png`, PNG, "image/png");
  const { error: photoError } = await db.from("piece_photos").insert({ piece_id: id, storage_path: photo, position: 1 });
  if (photoError) throw new Error(`insert photo: ${photoError.message}`);

  const renders: string[] = [];
  const previews: string[] = [];
  const rows = [];
  for (const candidate of [1, 2]) {
    const prefix = candidate === 1 ? `${id}/1` : `${id}/1/cand_${candidate}`;
    const renderPaths: Record<string, string> = {};
    for (const view of ["front", "left", "back", "three_quarter"]) {
      renderPaths[view] = await upload("renders", `${prefix}/${view}.png`, PNG, "image/png");
    }
    renderPaths.contact = await upload("renders", `${prefix}/contact.jpg`, PNG, "image/png");
    renders.push(...Object.values(renderPaths));
    const preview = await upload("previews", `${prefix}/model_preview.glb`, GLB, "model/gltf-binary");
    previews.push(preview);
    const errors = candidate === 1 ? { width: 0.021, height: -0.012, depth: 0.004 } : { width: 0.008, height: 0.011, depth: -0.003 };
    rows.push({
      piece_id: id,
      attempt: 1,
      provider: "tripo",
      candidate,
      preview_path: preview,
      glb_path: `${prefix}/model_web.glb`,
      usdz_path: options.withoutUsdz === candidate ? null : `${prefix}/model.usdz`,
      render_paths: renderPaths,
      meta: { provider: "tripo", candidate, post: { errors, errors_before_fit: errors, fit_box_applied: false } },
      max_error: Math.max(...Object.values(errors).map(Math.abs)),
      cost_usd: 0.3,
      selected: candidate === 1,
    });
  }
  const { data: models, error: modelError } = await db.from("piece_models").insert(rows).select("id, candidate");
  if (modelError || !models) throw new Error(`insert models: ${modelError?.message}`);
  const byCandidate = (n: number) => models.find((m) => m.candidate === n)!.id as string;

  return {
    id,
    name,
    modelIds: [byCandidate(1), byCandidate(2)],
    storage: [
      { bucket: "photos", paths: [photo] },
      { bucket: "renders", paths: renders },
      { bucket: "previews", paths: previews },
    ],
  };
}

export async function cleanupPiece(db: SupabaseClient, piece: SeededPiece | undefined): Promise<void> {
  if (!piece) return;
  for (const { bucket, paths } of piece.storage) await db.storage.from(bucket).remove(paths);
  await db.from("pieces").delete().eq("id", piece.id);
}

/** Playwright does not read Next's env files: load `.env.local` (never printed). */
export function loadEnv(): void {
  const file = path.join(process.cwd(), ".env.local");
  if (!process.env.SUPABASE_SERVICE_ROLE_KEY && existsSync(file)) process.loadEnvFile(file);
}

export function serviceClient(): SupabaseClient {
  loadEnv();
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) throw new Error("Faltan NEXT_PUBLIC_SUPABASE_URL o SUPABASE_SERVICE_ROLE_KEY en .env.local");
  return createClient(url, key, { auth: { persistSession: false, autoRefreshToken: false } });
}

export interface TestUser {
  id: string;
  email: string;
}

/** `test_*` user created through the Auth admin API; `admin` flips `profiles.is_admin`. */
export async function createTestUser(db: SupabaseClient, label: string, admin = false): Promise<TestUser> {
  const email = `test_${label}_${randomUUID().slice(0, 8)}@example.com`;
  const { data, error } = await db.auth.admin.createUser({ email, email_confirm: true });
  if (error || !data.user) throw new Error(`createUser: ${error?.message}`);
  if (admin) {
    const { error: upd } = await db.from("profiles").update({ is_admin: true }).eq("id", data.user.id);
    if (upd) throw new Error(`is_admin: ${upd.message}`);
  }
  return { id: data.user.id, email };
}

export async function deleteTestUser(db: SupabaseClient, user: TestUser | undefined): Promise<void> {
  if (user) await db.auth.admin.deleteUser(user.id); // cascades to profile, pieces, photos, models
}

/**
 * Signs the browser in without an email: a magic link generated by the admin API
 * is verified by the app's own `/auth/callback` (token_hash flow).
 */
export async function signIn(page: Page, db: SupabaseClient, email: string): Promise<void> {
  // Auth limits token verifications per IP; other suites hit the same project, so retry with a fresh link.
  for (let attempt = 1; ; attempt++) {
    const { data, error } = await db.auth.admin.generateLink({ type: "magiclink", email });
    if (error || !data.properties?.hashed_token) throw new Error(`generateLink: ${error?.message}`);
    await page.goto(`/auth/callback?token_hash=${data.properties.hashed_token}&type=magiclink`);
    if (/\/panel(\?|$)/.test(page.url()) || attempt === 4) break;
    await page.waitForTimeout(10_000 * attempt); // 429 over_request_rate_limit on /verify
  }
  await expect(page).toHaveURL(/\/panel(\?|$)/);
}

